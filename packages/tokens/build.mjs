import { mkdir, rm, writeFile } from 'node:fs/promises';
import StyleDictionary from 'style-dictionary';
import configs, { themes } from './style-dictionary.config.mjs';

const dist = new URL('./dist/', import.meta.url);
const banner = '/* Generated by @kerb/tokens. Do not edit. */\n';

const outputOf = (files, destination) => files.find((f) => f.destination === destination).output;

const themeNames = Object.keys(themes);
const css = {};
const tokens = {};
let shared;

for (const [index, theme] of themeNames.entries()) {
  const sd = new StyleDictionary(configs[index]);
  const cssFiles = await sd.formatPlatform('css');
  const jsonFiles = await sd.formatPlatform('json');
  shared ??= outputOf(cssFiles, 'shared.css');
  css[theme] = outputOf(cssFiles, `${theme}.css`);
  tokens[theme] = JSON.parse(outputOf(jsonFiles, `${theme}.json`));
}

// tokens.d.ts describes one theme's shape, so every theme must have the same keys
const shapeOf = (value) =>
  value !== null && typeof value === 'object' && !Array.isArray(value)
    ? Object.fromEntries(Object.entries(value).map(([k, v]) => [k, shapeOf(v)]))
    : Array.isArray(value)
      ? `${typeof value[0]}[]`
      : typeof value;

const shape = shapeOf(tokens[themeNames[0]]);
for (const theme of themeNames) {
  if (JSON.stringify(shapeOf(tokens[theme])) !== JSON.stringify(shape)) {
    throw new Error(`Theme "${theme}" does not define the same tokens as "${themeNames[0]}"`);
  }
}

const typeOf = (node, indent) =>
  typeof node === 'string'
    ? node
    : `{\n${Object.entries(node)
        .map(([k, v]) => `${indent}  ${JSON.stringify(k)}: ${typeOf(v, `${indent}  `)};`)
        .join('\n')}\n${indent}}`;

const dts = `${banner}
export type KerbTheme = ${themeNames.map((t) => `'${t}'`).join(' | ')};

/** Resolved token values for one theme. */
export interface KerbTokens ${typeOf(shape, '')}

declare const tokens: Record<KerbTheme, KerbTokens>;
export default tokens;
`;

await rm(dist, { recursive: true, force: true });
await mkdir(dist, { recursive: true });

const write = (name, content) => writeFile(new URL(name, dist), content);

await Promise.all([
  // Each theme file works on its own; kerb.css holds all three with the shared block once
  ...themeNames.map((theme) => write(`${theme}.css`, `${banner}\n${shared}\n${css[theme]}`)),
  write('kerb.css', `${banner}\n${[shared, ...themeNames.map((t) => css[t])].join('\n')}`),
  write('tokens.json', `${JSON.stringify(tokens, null, 2)}\n`),
  write('tokens.d.ts', dts),
]);

console.log(`@kerb/tokens: wrote kerb.css, ${themeNames.join('.css, ')}.css, tokens.json, tokens.d.ts`);
